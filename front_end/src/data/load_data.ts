import type { LsoaForces } from './coverage';
import type { DeprivationData } from './deprivation';
import type { CrimeDeprivationCorrelation, CrimeGroupCorrelation, Demography, LsoaArea, LsoaIndex, MonthCrimeData } from '../types';

/**
 * Fetch a static JSON file from /public and parse it.
 */
async function fetch_json<T>(url: string, signal?: AbortSignal): Promise<T> {
    const response = await fetch(url, { signal });

    if (!response.ok) {
        throw new Error(`Failed to load ${url} (${response.status})`);
    }

    return await response.json() as T;
}

/**
 * Load the census household deprivation counts per LSOA
 */
export function load_deprivation() {
    return fetch_json<DeprivationData>('/data/LSOA_2021_deprivation.json');
}

/**
 * Load the precomputed crime type × deprivation correlations
 */
export function load_crime_deprivation_correlation() {
    return fetch_json<CrimeDeprivationCorrelation>('/data/crime_deprivation_correlation.json');
}

/**
 * Load the code, name and bounding box of every LSOA on the map.
 */
export async function load_areas(): Promise<LsoaArea[]> {
    const index = await fetch_json<LsoaIndex>('/data/lsoa_index.json');
    return index.lsoa.map((lsoa, i) => ({ lsoa, lsoaNM: index.name[i], bbox: index.bbox[i] }));
}

/** The LSOA shapes, loaded by the map itself in a background worker */
export const BOUNDARIES_URL = '/data/lsoa_boundaries.json';

/**
 * Load the crime dataset for a given month (YYYY-MM).
 */
export function load_month(month: string, signal?: AbortSignal) {
    return fetch_json<MonthCrimeData>(`/data/crime/${month}.json`, signal);
}

/**
 * Load the precomputed crime type × ethnic group correlations
 * (generated by data_processing/scripts/correlation_maker.mjs).
 */
export function load_crime_group_correlation() {
    return fetch_json<CrimeGroupCorrelation>('/data/crime_group_correlation.json');
}

/**
 * Load the LSOA → police force lookup used to tell which areas have data each month
 * (generated by data_processing/scripts/update_crime_data.mjs).
 */
export function load_lsoa_forces() {
    return fetch_json<LsoaForces>('/data/lsoa_forces.json');
}

/**
 * Load the processed demographic dataset used in the area details.
 */
export function load_demography() {
    return fetch_json<Demography>('/data/LSOA_2021_demography.json');
}
